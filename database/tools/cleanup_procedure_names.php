<?php

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    exit("Run this tool from the command line.\n");
}

const VALID_NAME_PATTERN = '^(DST|LTP|NTK|NMT)_[A-Za-z0-9_]+$';
const EXPECTED_INVALID_COUNT = 147;
const EXPECTED_FINAL_DISTRIBUTION = [
    'DST' => 49,
    'LTP' => 49,
    'NMT' => 48,
    'NTK' => 48,
];
const REASSIGNMENTS = [
    'NMT_sp_direct_inbox' => 'LTP_sp_direct_inbox',
    'NMT_sp_direct_open' => 'LTP_sp_direct_open',
    'NMT_sp_direct_send' => 'LTP_sp_direct_send',
    'NMT_sp_direct_state' => 'LTP_sp_direct_state',
    'NMT_sp_direct_thread' => 'LTP_sp_direct_thread',
    'NMT_sp_admin_host_request_decide' => 'NTK_sp_admin_host_request_decide',
    'NMT_sp_admin_host_requests' => 'NTK_sp_admin_host_requests',
    'NMT_sp_host_request_status' => 'NTK_sp_host_request_status',
    'NMT_sp_host_request_submit' => 'NTK_sp_host_request_submit',
    'NMT_sp_facebook_identity_find' => 'DST_sp_facebook_identity_find',
    'NMT_sp_oauth_identity_find' => 'DST_sp_oauth_identity_find',
];

function quoteIdentifier(string $identifier): string
{
    return '`' . str_replace('`', '``', $identifier) . '`';
}

$projectRoot = dirname(__DIR__, 2);
require $projectRoot . DIRECTORY_SEPARATOR . 'core' . DIRECTORY_SEPARATOR . 'bootstrap.php';
$config = require $projectRoot . DIRECTORY_SEPARATOR . 'config' . DIRECTORY_SEPARATOR . 'database.php';
$database = (string) $config['database'];

$pdo = new PDO(
    sprintf(
        'mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4',
        $config['host'],
        $config['port'],
        $database
    ),
    $config['username'],
    $config['password'],
    [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
    ]
);

$invalidStatement = $pdo->prepare(
    "SELECT ROUTINE_NAME
       FROM information_schema.ROUTINES
      WHERE ROUTINE_SCHEMA = ?
        AND ROUTINE_TYPE = 'PROCEDURE'
        AND ROUTINE_NAME NOT REGEXP ?
      ORDER BY ROUTINE_NAME"
);
$invalidStatement->execute([$database, VALID_NAME_PATTERN]);
$invalidNames = $invalidStatement->fetchAll(PDO::FETCH_COLUMN);

if (count($invalidNames) !== EXPECTED_INVALID_COUNT) {
    throw new RuntimeException(
        'Expected ' . EXPECTED_INVALID_COUNT . ' invalid procedure names, found ' . count($invalidNames) . '.'
    );
}

$routineExists = $pdo->prepare(
    "SELECT COUNT(*)
       FROM information_schema.ROUTINES
      WHERE ROUTINE_SCHEMA = ?
        AND ROUTINE_TYPE = 'PROCEDURE'
        AND ROUTINE_NAME = ?"
);

$duplicateMapping = [];
foreach ($invalidNames as $invalidName) {
    if ($invalidName === 'DST_ sp_list_amenities') {
        $duplicateMapping[$invalidName] = 'DST_sp_list_amenities';
        continue;
    }

    $matches = [];
    foreach (array_keys(EXPECTED_FINAL_DISTRIBUTION) as $owner) {
        $candidate = $owner . '_' . trim($invalidName);
        $routineExists->execute([$database, $candidate]);
        if ((int) $routineExists->fetchColumn() === 1) {
            $matches[] = $candidate;
        }
    }

    if (count($matches) !== 1) {
        throw new RuntimeException(
            "Expected one prefixed replacement for {$invalidName}, found " . json_encode($matches)
        );
    }
    $duplicateMapping[$invalidName] = $matches[0];
}

foreach (REASSIGNMENTS as $oldName => $newName) {
    $routineExists->execute([$database, $oldName]);
    if ((int) $routineExists->fetchColumn() !== 1) {
        throw new RuntimeException("Missing source procedure: {$oldName}");
    }
    $routineExists->execute([$database, $newName]);
    if ((int) $routineExists->fetchColumn() !== 0) {
        throw new RuntimeException("Target procedure already exists: {$newName}");
    }
}

$outputDir = $projectRoot . DIRECTORY_SEPARATOR . 'database' . DIRECTORY_SEPARATOR . 'migrations';
$migrationFile = $outputDir . DIRECTORY_SEPARATOR . '20261112_cleanup_and_balance_procedure_names.sql';
$mappingFile = $outputDir . DIRECTORY_SEPARATOR . '20261112_procedure_name_changes.json';

$sql = "-- Clean stale unprefixed procedures and balance current procedure ownership.\n"
    . "-- Expected final distribution: DST 49, LTP 49, NMT 48, NTK 48.\n"
    . "-- Generated by database/tools/cleanup_procedure_names.php.\n\n"
    . "SET NAMES utf8mb4;\n"
    . "DELIMITER $$\n\n";

foreach (REASSIGNMENTS as $oldName => $newName) {
    $statement = $pdo->query('SHOW CREATE PROCEDURE ' . quoteIdentifier($oldName))->fetch();
    $createSql = $statement['Create Procedure'] ?? null;
    if (!is_string($createSql)) {
        throw new RuntimeException("Cannot read CREATE statement for {$oldName}");
    }

    $createSql = preg_replace(
        '/^CREATE\s+DEFINER\s*=\s*`[^`]+`@`[^`]+`\s+PROCEDURE/iu',
        'CREATE OR REPLACE PROCEDURE',
        $createSql,
        1,
        $definerCount
    );
    if ($definerCount !== 1) {
        throw new RuntimeException("Cannot remove environment-specific definer from {$oldName}");
    }

    $createSql = preg_replace(
        '/(\bPROCEDURE\s+)' . preg_quote(quoteIdentifier($oldName), '/') . '/iu',
        '$1' . quoteIdentifier($newName),
        $createSql,
        1,
        $declarationCount
    );
    if ($declarationCount !== 1) {
        throw new RuntimeException("Cannot rename declaration for {$oldName}");
    }

    foreach (REASSIGNMENTS as $calledOldName => $calledNewName) {
        $createSql = preg_replace(
            '/(\bCALL\s+)(?:' . preg_quote(quoteIdentifier($database), '/') . '\s*\.\s*)?'
                . preg_quote(quoteIdentifier($calledOldName), '/') . '(?=\s*\()/iu',
            '$1' . quoteIdentifier($calledNewName),
            $createSql
        );
        if (!str_contains($calledOldName, ' ')) {
            $createSql = preg_replace(
                '/(\bCALL\s+)(?:' . preg_quote($database, '/') . '\s*\.\s*)?'
                    . preg_quote($calledOldName, '/') . '(?=\s*\()/iu',
                '$1' . quoteIdentifier($calledNewName),
                $createSql
            );
        }
    }

    $sql .= 'DROP PROCEDURE IF EXISTS ' . quoteIdentifier($newName) . "$$\n";
    $sql .= $createSql . "$$\n\n";
}

$dropNames = array_values(array_unique(array_merge($invalidNames, array_keys(REASSIGNMENTS))));
sort($dropNames, SORT_NATURAL | SORT_FLAG_CASE);
foreach ($dropNames as $dropName) {
    $sql .= 'DROP PROCEDURE IF EXISTS ' . quoteIdentifier($dropName) . "$$\n";
}
$sql .= "\nDELIMITER ;\n";

file_put_contents($migrationFile, $sql);
file_put_contents(
    $mappingFile,
    json_encode(
        [
            'invalid_procedures_removed' => count($invalidNames),
            'stale_duplicate_mapping' => $duplicateMapping,
            'reassignments' => REASSIGNMENTS,
            'final_distribution' => EXPECTED_FINAL_DISTRIBUTION,
        ],
        JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
    ) . PHP_EOL
);

echo json_encode(
    [
        'invalid_procedures' => count($invalidNames),
        'stale_duplicates' => count($duplicateMapping),
        'reassignments' => count(REASSIGNMENTS),
        'final_distribution' => EXPECTED_FINAL_DISTRIBUTION,
        'migration' => $migrationFile,
        'mapping' => $mappingFile,
    ],
    JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
), PHP_EOL;
