<?php

declare(strict_types=1);

const DATABASE_NAME = 'db_home2home';
const OWNER_TARGETS = [
    'NMT' => 44,
    'NTK' => 43,
    'DST' => 43,
    'LTP' => 43,
];

function quoteIdentifier(string $identifier): string
{
    return '`' . str_replace('`', '``', $identifier) . '`';
}

$projectRoot = dirname(__DIR__, 2);
$outputDir = $projectRoot . DIRECTORY_SEPARATOR . 'database' . DIRECTORY_SEPARATOR . 'migrations';
if (!is_dir($outputDir) && !mkdir($outputDir, 0777, true) && !is_dir($outputDir)) {
    throw new RuntimeException("Cannot create migration directory: {$outputDir}");
}

$pdo = new PDO(
    'mysql:host=127.0.0.1;port=3306;dbname=' . DATABASE_NAME . ';charset=utf8mb4',
    'root',
    '',
    [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
    ]
);

$routineNames = $pdo->query(
    "SELECT ROUTINE_NAME
       FROM information_schema.ROUTINES
      WHERE ROUTINE_SCHEMA = " . $pdo->quote(DATABASE_NAME) . "
        AND ROUTINE_TYPE = 'PROCEDURE'
      ORDER BY ROUTINE_NAME"
)->fetchAll(PDO::FETCH_COLUMN);

if (count($routineNames) !== 173) {
    throw new RuntimeException('Expected 173 procedures, found ' . count($routineNames) . '.');
}

$assignments = [];
$unassigned = [];
$baseNames = [];
$ownerCounts = array_fill_keys(array_keys(OWNER_TARGETS), 0);

foreach ($routineNames as $oldName) {
    if (preg_match('/^(NMT|NTK|DST|LTP)_\s*(.+)$/u', $oldName, $matches) === 1) {
        $owner = $matches[1];
        $baseName = $matches[2];
        $assignments[$oldName] = ['owner' => $owner, 'base' => $baseName];
        ++$ownerCounts[$owner];
    } else {
        $baseName = $oldName;
        $unassigned[] = ['old' => $oldName, 'base' => $baseName];
    }

    $baseKey = mb_strtolower($baseName, 'UTF-8');
    if (isset($baseNames[$baseKey])) {
        throw new RuntimeException("Duplicate base routine name: {$baseName}");
    }
    $baseNames[$baseKey] = $oldName;
}

usort($unassigned, static fn(array $a, array $b): int => strnatcasecmp($a['base'], $b['base']));

while ($unassigned !== []) {
    $madeProgress = false;
    foreach (OWNER_TARGETS as $owner => $target) {
        if ($ownerCounts[$owner] >= $target || $unassigned === []) {
            continue;
        }

        $routine = array_shift($unassigned);
        $assignments[$routine['old']] = ['owner' => $owner, 'base' => $routine['base']];
        ++$ownerCounts[$owner];
        $madeProgress = true;
    }

    if (!$madeProgress) {
        throw new RuntimeException('Cannot satisfy the requested owner distribution.');
    }
}

if ($ownerCounts !== OWNER_TARGETS) {
    throw new RuntimeException('Unexpected distribution: ' . json_encode($ownerCounts));
}

$mapping = [];
foreach ($assignments as $oldName => $assignment) {
    $newName = $assignment['owner'] . '_' . $assignment['base'];
    if (mb_strlen($newName, 'UTF-8') > 64) {
        throw new RuntimeException("Routine name exceeds MariaDB's 64-character limit: {$newName}");
    }
    $mapping[$oldName] = $newName;
}

$newNames = array_values($mapping);
if (count(array_unique(array_map('mb_strtolower', $newNames))) !== count($newNames)) {
    throw new RuntimeException('The generated routine names are not unique.');
}

ksort($mapping, SORT_NATURAL | SORT_FLAG_CASE);
$sql = "-- Generated by database/tools/reassign_routine_owners.php\n"
    . "-- Distribution: NMT 44, NTK 43, DST 43, LTP 43\n"
    . "SET NAMES utf8mb4;\nDELIMITER $$\n\n";

foreach ($mapping as $oldName => $newName) {
    $statement = $pdo->query('SHOW CREATE PROCEDURE ' . quoteIdentifier($oldName))->fetch();
    $createSql = $statement['Create Procedure'] ?? null;
    if (!is_string($createSql)) {
        throw new RuntimeException("Cannot read CREATE statement for {$oldName}");
    }

    $oldDeclaration = '/(\bPROCEDURE\s+)' . preg_quote(quoteIdentifier($oldName), '/') . '/iu';
    $createSql = preg_replace($oldDeclaration, '$1' . quoteIdentifier($newName), $createSql, 1, $declarationCount);
    if ($declarationCount !== 1) {
        throw new RuntimeException("Cannot rename declaration for {$oldName}");
    }

    foreach ($mapping as $calledOldName => $calledNewName) {
        $callPattern = '/(\bCALL\s+)(?:' . preg_quote(quoteIdentifier(DATABASE_NAME), '/') . '\s*\.\s*)?'
            . preg_quote(quoteIdentifier($calledOldName), '/') . '(?=\s*\()/iu';
        $createSql = preg_replace($callPattern, '$1' . quoteIdentifier($calledNewName), $createSql);

        if (!str_contains($calledOldName, ' ')) {
            $unquotedCallPattern = '/(\bCALL\s+)(?:' . preg_quote(DATABASE_NAME, '/') . '\s*\.\s*)?'
                . preg_quote($calledOldName, '/') . '(?=\s*\()/iu';
            $createSql = preg_replace($unquotedCallPattern, '$1' . quoteIdentifier($calledNewName), $createSql);
        }
    }

    $sql .= 'DROP PROCEDURE IF EXISTS ' . quoteIdentifier($newName) . "$$\n";
    $sql .= $createSql . "$$\n\n";
}

foreach ($mapping as $oldName => $newName) {
    if ($oldName !== $newName) {
        $sql .= 'DROP PROCEDURE IF EXISTS ' . quoteIdentifier($oldName) . "$$\n";
    }
}

$sql .= "\nDELIMITER ;\n";

$migrationFile = $outputDir . DIRECTORY_SEPARATOR . '20261020_reassign_routine_owners.sql';
$mappingFile = $outputDir . DIRECTORY_SEPARATOR . '20261020_routine_owner_mapping.json';
file_put_contents($migrationFile, $sql);
file_put_contents(
    $mappingFile,
    json_encode(
        ['distribution' => $ownerCounts, 'mapping' => $mapping],
        JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
    ) . PHP_EOL
);

echo json_encode(
    [
        'procedures' => count($mapping),
        'distribution' => $ownerCounts,
        'migration' => $migrationFile,
        'mapping' => $mappingFile,
    ],
    JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
), PHP_EOL;
